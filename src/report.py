"""
report.py — daily decision report, written as markdown into the repo.

Renders in the GitHub mobile app, so it's readable anywhere with no hosting.
Run after ff_ingest.py parse.

    python src/report.py

Structure, top to bottom: what needs a decision today, your team as one table
(XI then bench, with the cost of each swap), and your own squad's price moves.
League-wide movers and recruitment live in reports/watchlist.md; how your
rivals behave lives in reports/behaviour.md.

SCORING lives in ffcore/score.py now, shared with rivals.py so that your
squad and theirs are ranked by the same arithmetic:

    score = shrunk points-per-match  x  P(start)

It is a RANKING INDEX, not a points forecast, and it cannot know three
things — all flagged in the report rather than hidden: promoted-side players
carry an assumed baseline, absence from the probable-XI page is not the same
as a blank percentage there, and none of it has been checked against reality
yet. Every snapshot appends the whole squad, XI and bench, with the inputs
that produced each score, to data/decisions/squad_log.csv, so that once
jornadas exist you can ask what the ranking cost you.

MIGRATED onto ffcore. Four things changed in substance:

  * fold(), num(), eur(), read_csv(), latest_only(), parse_stamp() and
    input_path() are gone — they were local copies. norm() in particular
    now matches the rest of the repo, so a name with an apostrophe or an
    initial joins the same way here as it does in squads.py.
  * The scorer is imported, not defined. Tuning SHRINK_K used to require
    editing two files that could silently disagree.
  * Cash comes from ffcore.league, which also reads rival balances and
    understands a time-of-day on the anchor. The old regex read the first
    number in the file and assumed midnight.
  * Your squad comes from the ledger via ffcore.league. inputs/squad.txt is
    still generated by squads.py and still works as a fallback, but it is no
    longer the source of truth.
"""

from __future__ import annotations

import os
import re
import sys
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from ffcore.league import League  # noqa: E402
from ffcore.parse import money, ratio  # noqa: E402
from ffcore.score import (ABSENT_START, MAX_SLOT, NEUTRAL_START,  # noqa: E402
                          SLOT_LABEL, SLOT_MIN, THIN, Scorer, pick_xi,
                          squad_pool)
from ffcore.tidy import (DECISIONS, MADRID, REPORTS, SEASON,  # noqa: E402
                         append_csv, input_path, latest_only, ledger_stamp,
                         load_market, load_xi, read_csv, snapshot_stamp,
                         write_lines)

HISTORY = REPORTS / "history"

STALE_HOURS = 14.0
MOVER_PCT = 1.0           # squad price moves worth printing

# Name particles that stay lowercase when title-casing a folded name.
# "le"/"el"/"la" are deliberately absent: Le Normand and El Hilali are far
# more common in this league than "de la Fuente" losing its lowercase.
PARTICLES = {"de", "del", "van", "von", "der", "den", "di", "da", "dos",
             "do", "y", "bin", "ibn", "ter"}


def title_name(s: str) -> str:
    """market.csv hands us folded names; make them readable again.

    Accents survive (they're in the source string), particles stay lowercase,
    hyphenated parts are capitalised on both sides. Moves to ffcore/render.py
    when the other reports are migrated.
    """
    s = (s or "").strip()
    if not s or s != s.lower():
        return s  # already cased — leave it alone
    words = []
    for i, w in enumerate(s.split()):
        if i and w in PARTICLES:
            words.append(w)
        else:
            words.append("-".join(p[:1].upper() + p[1:] for p in w.split("-")))
    return " ".join(words)


def eur(v) -> str:
    if v is None:
        return "—"
    v = float(v)
    if abs(v) >= 1_000_000:
        return f"{v/1_000_000:.2f}M"
    if abs(v) >= 1_000:
        return f"{v/1_000:.0f}K"
    return f"{v:.0f}"


def load_history() -> tuple[dict, str]:
    """{normalised name: {'pts','pj'}} from the newest points_*.csv."""
    from ffcore.text import norm
    files = sorted(SEASON.glob("points_*.csv")) if SEASON.exists() else []
    if not files:
        return {}, ""
    out: dict[str, dict] = {}
    for r in read_csv(files[-1]):
        rec = {"pts": ratio(r.get("points")) or 0.0,
               "pj": ratio(r.get("games")) or 0.0}
        for key in (r.get("player_name"), r.get("player_name_full")):
            if key:
                out.setdefault(norm(key), rec)
    return out, files[-1].stem.replace("points_", "")


def load_squad_file() -> list[str]:
    """inputs/squad.txt — fallback only. The ledger is the source of truth."""
    path = input_path("squad.txt")
    if not path.exists():
        return []
    return [ln.strip() for ln in path.read_text(encoding="utf-8").splitlines()
            if ln.strip() and not ln.strip().startswith("#")]


def load_deadline():
    """inputs/deadline.txt: next lock, e.g. 2026-08-15T18:30 (Madrid time)."""
    path = input_path("deadline.txt")
    if not path.exists():
        return None
    body = "\n".join(ln.split("#")[0] for ln in
                     path.read_text(encoding="utf-8").splitlines())
    m = re.search(r"\d{4}-\d{2}-\d{2}[T ]?\d{0,2}:?\d{0,2}", body)
    return ledger_stamp(m.group(0)) if m else None


def squad_names(lg) -> tuple[list[str], str]:
    """Your roster, and where it came from."""
    if lg is not None:
        mine = lg.managers.get(lg.cfg.me)
        if mine and mine.players:
            by_key = lg.market.latest() if lg.market else {}
            return ([by_key.get(k, {}).get("name", k) for k in mine.players],
                    "ledger")
    return load_squad_file(), "squad.txt"


def log_squad(observed, players, chosen, formation, total, deadline,
              obs_dt) -> None:
    """Append-only record of every recommendation, for scoring later.

    One row per player per snapshot — long format, so a scorer can group by
    snapshot without parsing packed strings. hours_to_lock is stored rather
    than an at-lock flag, because a run cannot know whether a later snapshot
    will still beat the deadline: the scorer picks, per jornada, the row with
    the smallest non-negative value.

    The bench is logged too. Without it "what did the ranking cost me" is
    unanswerable after the fact, and that is the whole point of keeping this.
    """
    path = DECISIONS / "squad_log.csv"
    if observed in {r.get("observed_at") for r in read_csv(path)}:
        return
    htl = ""
    if deadline and obs_dt:
        htl = f"{(deadline - obs_dt).total_seconds() / 3600:.1f}"
    cols = ["observed_at", "hours_to_lock", "formation", "index_total",
            "player", "pos", "slot", "start_pct", "start_source", "status",
            "assumed", "value", "score", "picked"]
    rows = []
    for p in players:
        src = ("read" if p["pct"] is not None
               else "listed_blank" if p["on_page"] else "absent")
        rows.append({
            "observed_at": observed, "hours_to_lock": htl,
            "formation": "-".join(str(x) for x in formation),
            "index_total": f"{total:.2f}",
            "player": p["name"], "pos": p["pos"], "slot": p["slot"],
            "start_pct": "" if p["pct"] is None else f"{p['pct']:.0f}",
            "start_source": src, "status": p["status"] or "ok",
            "assumed": int(bool(p["assumed"])),
            "value": f"{p['value']:.0f}", "score": f"{p['score']:.3f}",
            "picked": int(id(p) in chosen),
        })
    append_csv(path, rows, cols)


def main() -> None:
    market = latest_only(load_market())
    xi_rows = latest_only(load_xi())

    REPORTS.mkdir(exist_ok=True)
    HISTORY.mkdir(parents=True, exist_ok=True)

    if not market:
        write_lines(REPORTS / "latest.md", [
            "# Fantasy report", "",
            "No market data in `data/tidy/market.csv`. "
            "Did `ff_ingest.py parse` run?"])
        print("no market data; wrote placeholder report")
        return

    try:
        lg = League.load()
    except SystemExit as exc:
        # rosters_initial.txt missing — fall back to squad.txt so a
        # half-configured repo still produces a report.
        print("league not loaded (%s); using squad.txt" % exc)
        lg = None

    hist, hist_label = load_history()
    shrink_k = lg.cfg.shrink_k if lg else 8.0
    sc = Scorer(market, xi_rows, hist, shrink_k=shrink_k)

    observed = market[0]["observed_at"]
    obs_dt = snapshot_stamp(observed)
    now = datetime.now(timezone.utc)
    age_h = (now - obs_dt).total_seconds() / 3600 if obs_dt else None

    # --- build squad records ---------------------------------------------
    squad, squad_src = squad_names(lg)
    scored, missing = sc.score_squad(squad)
    players = []
    for s in scored:
        row = s.as_row()
        row["name"] = title_name(row["name"])
        players.append(row)
    squad_value = sum(p["value"] for p in players)

    pool = squad_pool(players)
    best = pick_xi(pool) if players else None
    chosen = {id(p) for p in best[2]} if best else set()

    # --- header -----------------------------------------------------------
    out: list[str] = [f"# Fantasy report — {observed}", ""]

    alerts: list[str] = []
    if age_h is not None and age_h > STALE_HOURS:
        alerts.append(f"**Data is {age_h:.0f}h old** — the ingest workflow may "
                      "have failed. Everything below is that snapshot.")
    deadline = load_deadline()
    if deadline:
        left = (deadline - now).total_seconds() / 3600
        if left < 0:
            alerts.append("**Deadline passed** — update `inputs/deadline.txt`.")
        elif left < 48:
            alerts.append(f"**Locks in {left:.0f}h.** Probable XIs are at their "
                          "most reliable now.")
        else:
            alerts.append(f"Locks in {left/24:.0f} days — readings will still "
                          "move, so this is provisional.")

    if best:
        for k, n in THIN.items():
            have = len(pool.get(k, []))
            if have < n:
                alerts.append(f"**Only {have} {SLOT_LABEL[k]}"
                              f"{'s' if have != 1 else ''}** — one knock and "
                              "you can't field a legal XI.")
        hurt = [p["name"] for p in best[2] if p["status"]]
        if hurt:
            alerts.append("**Flagged in the XI:** " + ", ".join(hurt) + ".")
        guessed = [p["name"] for p in best[2] if p["assumed"]]
        if guessed:
            alerts.append(f"**{len(guessed)} of the XI are unmodelled** "
                          f"({', '.join(guessed)}) — no LaLiga record, so "
                          "they're carrying an assumed baseline, not an "
                          "earned one.")
    if missing:
        alerts.append("**Not found in the market:** "
                      + ", ".join(f"`{m}`" for m in missing)
                      + " — check them with find_slug.py.")

    if alerts:
        out += ["## Needs a decision", ""] + [f"- {a}" for a in alerts] + [""]

    # --- money ------------------------------------------------------------
    cash = lg[lg.cfg.me].cash if lg and lg.cfg.me in lg.managers else None
    line = f"**Squad {eur(squad_value)}**"
    if cash and cash.value is not None:
        line += (f" · cash {cash.label()} · total "
                 f"{eur(squad_value + cash.value)}")
        if cash.confidence != "known":
            line += " — cash is an estimate; record a balance in `cash.txt`."
        else:
            last_tx = max((t.get("date") or "" for t in lg.txns), default="")
            anchor = re.search(r"\d{4}-\d{2}-\d{2}", cash.basis or "")
            if anchor and last_tx and last_tx[:10] > anchor.group(0):
                line += (f" — balance last checked {anchor.group(0)}, but the "
                         f"ledger moved on {last_tx[:10]}. Re-check it.")
    else:
        line += " — add `inputs/cash.txt` to see cash alongside it."
    out += [line, "",
            "Compare squad value with the app; a mismatch means a name "
            f"matched the wrong player. Roster read from the {squad_src}.", ""]

    # --- team -------------------------------------------------------------
    out += ["## Team", ""]
    if not players:
        out += ["_Empty — no roster found. Check `inputs/rosters_initial.txt` "
                "and `inputs/transactions.csv`._", ""]
    elif best is None:
        short = [SLOT_LABEL[k] for k, n in SLOT_MIN.items()
                 if len(pool.get(k, [])) < n]
        out += ["_No legal XI from this squad — short of: "
                + (", ".join(short) or "?") + "._", ""]
    else:
        tot, (d, m, f), picked = best
        out += [f"**{d}-{m}-{f}** · index {tot:.1f} "
                "(a ranking number, not a points forecast)", "",
                "| | Player | Start% | Value | 24h | Score | Last season |",
                "|---|---|--:|--:|--:|--:|---|"]
        for slot in ("POR", "DEF", "MED", "DEL"):
            for p in [x for x in picked if x["slot"] == slot]:
                mark = {"injured": " **INJ**",
                        "doubt": " **?**"}.get(p["status"], "")
                pct_s = (f"{p['pct']:.0f}%" if p["pct"] is not None
                         else ("~" if p["on_page"] else "!") +
                         f"{NEUTRAL_START if p['on_page'] else ABSENT_START:.0f}%")
                why = f"**{p['why']}**" if p["assumed"] else p["why"]
                out.append(f"| {slot} | {p['name']}{mark} | {pct_s} | "
                           f"{eur(p['value'])} | {eur(p['delta_1d'])} | "
                           f"{p['score']:.1f} | {why} |")
        out.append("")

        bench = [p for p in players if id(p) not in chosen]
        out += ["**Bench** — gap is what the XI index loses by playing him "
                "instead, after re-picking the formation. €/pt is his value "
                "per point of score: the sell shortlist, worst first.", ""]
        if not bench:
            out += ["_Nobody spare._", ""]
        else:
            rank = {id(p): i for v in pool.values() for i, p in enumerate(v)}
            rows = []
            for p in bench:
                forced = pick_xi(pool, force=p) if p["slot"] else None
                gap = (forced[0] - tot) if forced else None
                cpp = p["value"] / p["score"] if p["score"] > 0.05 \
                    else float("inf")
                if p["status"] == "injured":
                    why = "injured"
                elif p["slot"] and rank.get(id(p), 0) >= MAX_SLOT[p["slot"]]:
                    nth = rank[id(p)] + 1
                    sfx = ("th" if nth % 100 in (11, 12, 13)
                           else {1: "st", 2: "nd", 3: "rd"}.get(nth % 10, "th"))
                    why = (f"{nth}{sfx} {p['slot']} — only "
                           f"{MAX_SLOT[p['slot']]} can ever play")
                elif p["delta_pct"] >= MOVER_PCT:
                    why = "rising — sell into strength"
                elif p["pos"] == "entrenador":
                    why = "coach slot"
                elif gap is not None and gap > -0.15:
                    why = "as good as the man ahead"
                else:
                    why = "outscored"
                rows.append((cpp, p, gap, why))
            rows.sort(key=lambda t: t[0], reverse=True)
            out += ["| Player | Pos | Value | Score | Gap | €/pt | Why |",
                    "|---|---|--:|--:|--:|--:|---|"]
            for cpp, p, gap, why in rows:
                out.append(
                    f"| {p['name']} | {p['pos'][:3]} | {eur(p['value'])} | "
                    f"{p['score']:.1f} | "
                    f"{'—' if gap is None else format(gap, '+.1f')} | "
                    f"{'—' if cpp == float('inf') else eur(cpp)} | {why} |")
            out += ["", "_A sale lands above or below value depending on who "
                        "bids. Who is short in this position, and who can "
                        "still afford you, is in `reports/behaviour.md`._", ""]

        log_squad(observed, players, chosen, (d, m, f), tot, deadline, obs_dt)

    # --- your movers ------------------------------------------------------
    movers = sorted((p for p in players if abs(p["delta_pct"]) >= MOVER_PCT),
                    key=lambda p: p["delta_pct"], reverse=True)
    out += [f"## Your movers (24h, over {MOVER_PCT:.0f}%)", ""]
    if not movers:
        out += ["_Nothing in your squad moved much._", ""]
    else:
        out += ["| Player | Value | 24h | % |", "|---|--:|--:|--:|"]
        for p in movers:
            out.append(f"| {p['name']} | {eur(p['value'])} | "
                       f"{eur(p['delta_1d'])} | {p['delta_pct']:+.2f}% |")
        out.append("")

    out += [
        "---",
        "",
        f"_{len(market)} players tracked, {len(sc.start_pct)} with a "
        "probable-XI reading. Who to buy is in `reports/watchlist.md`; how "
        "your rivals bid is in `reports/behaviour.md`._",
        "",
        f"_Score = shrunk pts/match (K={shrink_k:.0f}"
        + (f", {hist_label}" if hist_label else ", **no points baseline**")
        + ") × P(start), from `ffcore/score.py` — the same scorer rivals.py "
          "uses. Recommended XIs are logged to "
          "`data/decisions/squad_log.csv` for scoring against reality later._",
        "",
        f"_Generated {now:%Y-%m-%d %H:%M} UTC._",
    ]

    write_lines(REPORTS / "latest.md", out)
    write_lines(HISTORY / f"{observed[:10]}.md", out)


if __name__ == "__main__":
    main()
