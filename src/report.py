def squad_names(lg) -> tuple[list[str], str]:
    """Your roster, and where it came from."""
    if lg is not None:
        mine = lg.managers.get(lg.cfg.me)
        if mine and mine.players:
            by_key = lg.market.latest() if lg.market else {}
            return ([by_key.get(k, {}).get("name", k) for k in mine.players],
                    "ledger")
    return load_squad_file(), "squad.txt"


def rival_ceiling(lg) -> float | None:
    """Largest bid any rival could still make, or None if any cash is unknown.

    An unknown balance is not a zero. Returning None where one rival's cash
    cannot be reconstructed is what stops suggest() telling you to bid the
    floor against someone who can outspend you.
    """
    bids = [m.max_bid for m in lg if m.handle != lg.cfg.me]
    if not bids or any(b is None for b in bids):
        return None
    return max(bids)


def sec_slate(lg, sc, by_key, pool, tot, slate, prem, cash_value,
              rival_max, snaps, sell_prem=None,
              bands=None) -> tuple[list[str], int, int]:
    """Today's slate, priced. The only section that answers 'what do I do now'.

    Everything else in this report describes a position; this one is a list of
    purchases you can make in the next few minutes, so it leads. XI gain is the
    change in the ranking index from owning him and re-picking the formation —
    it is what he is worth to you, and it is frequently negative for a player
    the watchlist ranks highly, because your own eleven is the benchmark.
    """
    on_offer, unresolved, ambiguous, auto = slate
    out: list[str] = []

    owned = {k: lg.owner[k] for k in on_offer if k in lg.owner}

    rows = []
    for k in on_offer:
        if k in owned:
            continue
        rec = by_key.get(k)
        if not rec:
            continue
        cand = sc.score(rec).as_row()
        cand["name"] = title_name(cand["name"])
        g = gain(pool, cand, tot) if tot is not None else None
        adv = suggest(cand["value"], prem, cash_value, rival_max)
        # How far below the thin threshold you are in HIS position. This is
        # what turns a negative-gain forward into cover rather than a pass.
        slot = cand.get("slot")
        short_by = (max(0, THIN[slot] - len(pool.get(slot, [])))
                    if slot in THIN else 0)
        daily_pct, n_drift = (bands or {}).get(band_of(cand["value"]),
                                               (0.0, 0))
        fr = friction(cand["value"], prem, sell_prem, daily_pct, n_drift)
        rows.append((cand, g, adv, short_by, fr))

    # Best upgrade first. A player who cannot start sorts last whatever his
    # score, because the question here is what he adds to YOUR eleven.
    # Cover first when you cannot field a legal XI without it, then by gain.
    rows.sort(key=lambda r: (-r[3] if r[1] is not None and r[1] <= 0 else 0,
                             r[1] is None, -(r[1] or 0.0), -r[0]["score"]))
    better = sum(1 for _, g, _, _, _ in rows if g is not None and g > 0)
    covers = sum(1 for _, g, a, sb, _ in rows
                 if sb > 0 and a.low is not None and g is not None)

    out += ["## 4. Anything to do in the market?", "",
            "**%d on offer, %d improve your XI%s.**"
            % (len(rows), better,
               ", %d cover a position you are short in" % covers
               if covers else ""), ""]
    if not rows:
        out += ["_Every name you pasted is either already owned or missing "
                "from the market data._", ""]
    else:
        out += ["| Player | Pos | Value | Start% | XI gain | Bid | Cost/pt | "
                "Competition | Verdict |",
                "|---|---|--:|--:|--:|--:|--:|---|---|"]
        for cand, g, adv, short_by, fr in rows:
            band = ("—" if adv.low is None
                    else eur(adv.low) if abs(adv.high - adv.low) < 1_000
                    else "%s–%s" % (eur(adv.low), eur(adv.high)))
            cpp = fr.per_point(g) if fr else None
            out.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                cand["name"], (cand["pos"] or "—")[:3], eur(cand["value"]),
                "—" if cand["pct"] is None else "%.0f%%" % cand["pct"],
                "—" if g is None else "%+.1f" % g,
                band, "—" if cpp is None else eur(cpp),
                demand_summary(cand, lg, snaps),
                verdict(g, adv, short_by)))
        out += ["",
                "**Cost/pt** is what the marginal point actually costs, and "
                "it is not the price: a purchase is closer to a loan than a "
                "spend, because the value comes back when you sell. It is the "
                "premium you pay over the floor plus the value expected to "
                "drain away over %d days — NOT the price, and NOT the exit. "
                "The app pays value give or take %s on a sale, which on a "
                "large player is bigger than both other terms together; that "
                "swing is a coin flip, so it is stated here rather than "
                "averaged into a number that would look like a price. "
                "Drift is a flat mean within his price band, over readings "
                "taken before a ball was kicked — expect it to move harder "
                "once results land."
                % (HOLD_DAYS,
                   ("%.0f%%" % sell_prem.swing() if sell_prem
                    else "about a tenth")),
                "",
                "Competition is demand, not roster counts: the rivals whose "
                "XI actually improves with him, strongest threat first — "
                "`?` cash unknown (treat as live), `(n broke)` want him but "
                "cannot pay the floor. The full manager-by-manager matrix is "
                "in `reports/rivals.md`.", "",
                "Bid is the floor plus what this league has actually paid over "
                "it: %s.%s A dozen deals is not a distribution — the range is "
                "what has happened, not a chance of winning, and every one of "
                "them is a bid that won."
                % (prem.label() if prem else
                   "no priced purchase yet, so these are floors",
                   ("" if not prem else
                    " %d of those %d went at the floor itself, so the minimum "
                    "is not a number known to lose." % (prem.at_floor, prem.n)
                    if prem.at_floor else
                    " None of those %d went at the floor." % prem.n)), ""]
        if rival_max is None:
            out += ["_At least one rival's cash is an estimate, so no bid here "
                    "assumes you are unopposed._", ""]
        if cash_value is None:
            out += ["_Your own balance is not a recorded number, so no bid is "
                    "capped by what you actually have. Put it in "
                    "`inputs/cash.txt`._", ""]

    if owned:
        out += ["Already owned, so not a purchase: %s." % ", ".join(
            "%s (%s)" % (by_key.get(k, {}).get("name", k),
                         "you" if h == lg.cfg.me else h)
            for k, h in sorted(owned.items())), ""]

    if auto:
        # Printed, not hidden: this is the one place the repo guesses between
        # candidates, and it guesses off a ledger you maintain by hand. If a
        # line here names the wrong player, the fix is a missing row in
        # transactions.csv (issue #26).
        out += ["**Placed by ownership, not by the name.** The app deals free "
                "agents, so a candidate somebody already holds is not the one "
                "on offer — check these if one looks wrong:", ""]
        out += ["- " + a for a in auto] + [""]

    if unresolved or ambiguous:
        # A heading, not bold text, so digest.py prints it once instead of
        # repeating the watchlist's copy of the same list.
        out += ["## Names I could not place", "",
                "OCR mangled these past matching, so they are missing from "
                "the table above — re-read them off the app if one matters.",
                ""]
        out += ["- **%s** — no match" % u for u in unresolved]
        out += ["- **%s** — could be %s" % (raw, ", ".join(c))
                for raw, c in ambiguous]
        out.append("")
    return out, len(rows), better


def log_squad(observed, players, chosen, formation, total, deadline,
              obs_dt) -> None:
    """Append-only record of every recommendation, for scoring later.

    One row per player per snapshot — long format, so a scorer can group by
    snapshot without parsing packed strings. hours_to_lock is stored rather
    than an at-lock flag, because a run cannot know whether a later snapshot
    will still beat the deadline: the scorer picks, per jornada, the row with
    the smallest non-negative value.

    The bench is logged too. Without it "what did the ranking cost me" is
    unanswerable after the fact, and that is the whole point of keeping this.
    """
    path = DECISIONS / "squad_log.csv"
    if observed in {r.get("observed_at") for r in read_csv(path)}:
        return
    htl = ""
    if deadline and obs_dt:
        htl = f"{(deadline - obs_dt).total_seconds() / 3600:.1f}"
    cols = ["observed_at", "hours_to_lock", "formation", "index_total",
            "player", "pos", "slot", "start_pct", "start_source", "status",
            "assumed", "value", "score", "picked"]
    rows = []
    for p in players:
        src = ("read" if p["pct"] is not None
               else "listed_blank" if p["on_page"] else "absent")
        rows.append({
            "observed_at": observed, "hours_to_lock": htl,
            "formation": "-".join(str(x) for x in formation),
            "index_total": f"{total:.2f}",
            "player": p["name"], "pos": p["pos"], "slot": p["slot"],
            "start_pct": "" if p["pct"] is None else f"{p['pct']:.0f}",
            "start_source": src, "status": p["status"] or "ok",
            "assumed": int(bool(p["assumed"])),
            "value": f"{p['value']:.0f}", "score": f"{p['score']:.3f}",
            "picked": int(id(p) in chosen),
        })
    append_csv(path, rows, cols)


